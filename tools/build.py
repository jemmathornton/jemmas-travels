"""Build site/js/data.js from data/ (trips, countries, posts) and stamp file fingerprints into site/index.html.

Run: python -X utf8 tools/build.py
Posts live in data/posts/<trip id>/<nn>.md: a header between --- lines, then the text.
Header keys: title, days (e.g. 1 or 2-4) or dates (2024-09-05 or 2024-09-05 to 2024-09-07), place,
photos (file names in site/photos/<trip id>/, comma-separated; a number = that many placeholder frames),
placeholder (yes = shown marked as a placeholder).
"""
import hashlib
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from post_file import read_post_file  # noqa: E402  (the one post parser, shared with check_data.py)

ROOT = Path(os.environ.get("TRAVELS_ROOT", Path(__file__).resolve().parent.parent))
DATA = ROOT / "data"
SITE = ROOT / "site"


def read_post(path: Path, trip_id: str) -> dict:
    meta, paras = read_post_file(path)
    if meta is None:
        raise SystemExit(f"{path}: needs a header between --- lines")
    photos = meta.get("photos", "").strip()
    if photos.isdigit():
        photo_list = [None] * int(photos)  # placeholder frames
    else:
        photo_list = [p.strip() for p in photos.split(",") if p.strip()]
        for p in photo_list:
            if not (SITE / "photos" / trip_id / p).exists():
                print(f"warning: {path.name}: photo {p} not found in site/photos/{trip_id}/", file=sys.stderr)
    return {
        "trip": trip_id,
        "slug": path.stem,
        "title": meta.get("title", ""),
        "days": meta.get("days", ""),
        "dates": meta.get("dates", ""),
        "place": meta.get("place", ""),
        "photos": photo_list,
        "placeholder": meta.get("placeholder", "").lower() in ("yes", "true"),
        "text": paras,
    }


def build() -> dict:
    trips = json.loads((DATA / "trips.json").read_text(encoding="utf-8"))["trips"]
    countries = json.loads((DATA / "countries.json").read_text(encoding="utf-8"))
    ids = {t["id"] for t in trips}
    for t in trips:
        for c in t["countries"]:
            if c not in countries["countries"]:
                raise SystemExit(f"trip {t['id']}: country {c} missing from data/countries.json")
    posts = []
    posts_dir = DATA / "posts"
    if posts_dir.exists():
        for d in sorted(posts_dir.iterdir()):
            if not d.is_dir():
                continue
            if d.name not in ids:
                raise SystemExit(f"data/posts/{d.name}: no trip with that id in trips.json")
            for f in sorted(d.glob("*.md")):
                posts.append(read_post(f, d.name))
    return {
        "trips": trips,
        "countries": countries["countries"],
        "continentTotals": countries["continentTotals"],
        "home": countries["home"],
        "homeTown": countries.get("homeTown", ""),
        "homeAt": countries.get("homeAt"),
        "posts": posts,
    }


def fingerprint(path: Path) -> str:
    return hashlib.sha1(path.read_bytes()).hexdigest()[:8]


def main():
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import check_data
    found = check_data.problems(ROOT)
    if found:
        for p in found:
            print(p, file=sys.stderr)
        raise SystemExit(f"not built: {len(found)} problem(s) in data/ (python -X utf8 tools/check_data.py lists them)")
    data = build()
    out = SITE / "js" / "data.js"
    out.write_text("// Generated by tools/build.py from data/ - never edit by hand.\nconst TRAVELS = "
                   + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    index = SITE / "index.html"
    html = index.read_text(encoding="utf-8")
    for name in ("js/family-load.js", "site.css", "js/icons.js", "js/data.js", "js/world.js", "js/map.js", "js/app.js"):
        p = SITE / name
        if p.exists():
            html = re.sub(re.escape(name) + r"\?v=[0-9a-f]+", f"{name}?v={fingerprint(p)}", html)
    index.write_text(html, encoding="utf-8")
    print(f"built: {len(data['trips'])} trips, {len(data['posts'])} posts")


if __name__ == "__main__":
    main()
