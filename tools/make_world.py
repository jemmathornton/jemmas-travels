"""Turn Natural Earth country shapes (world-atlas 2.0.2 TopoJSON, imports/world-atlas-2.0.2/) into site/js/world.js.

Run: python -I -X utf8 tools/make_world.py
Writes WORLD = {lo: {...}, hi: {...}}: each country id (ISO numeric) -> [name, rings], rings as flat [lon, lat, lon, lat, ...]
rounded to 2 decimals. lo = 1:110m (world maps), hi = 1:50m (zoomed-in trip and country maps). Antarctica left out.
Natural Earth is public domain; world-atlas (Mike Bostock) is ISC: licence copied next to the output.
"""
import json
import os
import shutil
from pathlib import Path

ROOT = Path(os.environ.get("TRAVELS_ROOT", Path(__file__).resolve().parent.parent))
SRC = ROOT / "imports" / "world-atlas-2.0.2"
OUT = ROOT / "site" / "js"


def decode(path, step):
    topo = json.loads(path.read_text(encoding="utf-8"))
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx; y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)

    def ring(idx):
        pts = []
        for i in idx:
            a = arcs[i] if i >= 0 else arcs[~i][::-1]
            pts.extend(a if not pts else a[1:])
        # a ring that crosses the 180° line (eastern Russia, Fiji) jumps from +180 to -180: make it continuous
        # by moving its western points east (the part past 180 falls off the right edge of the map)
        if any(abs(pts[j][0] - pts[j - 1][0]) > 180 for j in range(1, len(pts))):
            pts = [(lon + 360 if lon < 0 else lon, lat) for lon, lat in pts]
        flat, last = [], None
        for lon, lat in pts:
            p = (round(round(lon / step) * step, 2), round(round(lat / step) * step, 2))
            if p != last:
                flat.extend(p); last = p
        return flat if len(flat) >= 8 else None

    out = {}
    for g in topo["objects"]["countries"]["geometries"]:
        cid = g.get("id") or "x" + g["properties"]["name"][:3]
        if cid == "010":  # Antarctica
            continue
        polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]] if g["type"] == "Polygon" else []
        rings = [r for poly in polys for r in (ring(x) for x in poly) if r]
        if rings:
            out[cid] = [g["properties"]["name"], rings]
    return out


def main():
    lo = decode(SRC / "countries-110m.json", 0.01)
    hi = decode(SRC / "countries-50m.json", 0.02)
    text = ("// Country shapes from Natural Earth (public domain) via world-atlas 2.0.2 (ISC, see LICENSE-world-atlas.txt).\n"
            "// Generated by tools/make_world.py - never edit by hand.\n"
            "const WORLD = " + json.dumps({"lo": lo, "hi": hi}, separators=(",", ":")) + ";\n")
    (OUT / "world.js").write_text(text, encoding="utf-8")
    shutil.copy(SRC / "LICENSE", OUT / "LICENSE-world-atlas.txt")
    print(f"world.js: {len(lo)} countries (110m), {len(hi)} (50m), {len(text) // 1024} KB")


if __name__ == "__main__":
    main()
